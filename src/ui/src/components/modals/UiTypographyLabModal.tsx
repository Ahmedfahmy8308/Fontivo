      output = `fontSize: {\n`;
      typeLevels.forEach((lvl) => {
        const px = Math.round(baseSize * lvl.mult);
        const rem = (px / 16).toFixed(3);
        output += `  '${lvl.name.toLowerCase()}': ['${rem}rem', { lineHeight: '1.4' }],\n`;
      });
