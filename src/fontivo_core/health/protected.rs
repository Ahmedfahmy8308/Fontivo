pub fn strip_registry_font_suffix(raw: &str) -> String {
    let mut s = raw.trim().to_string();
    for suffix in [
        " (TrueType & OpenType)",
        " (TrueType)",
        " (OpenType)",
        " (All types)",
    ] {
        if s.len() > suffix.len() {
            let split_idx = s.len() - suffix.len();
            if s.is_char_boundary(split_idx) && s[split_idx..].eq_ignore_ascii_case(suffix) {
                s.truncate(split_idx);
                s = s.trim().to_string();
                break;
            }
        }
    }
    s
}

